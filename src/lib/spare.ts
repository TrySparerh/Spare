/**
 * Spare domain math — pure, bigint, USDG base units.
 *
 * The rules, linked wallets and target mix now live ON-CHAIN (RuleRegistry,
 * ElectionRegistry); the apps read them with wagmi and nothing here stores a
 * copy. What stays in this file is arithmetic that must agree with the
 * contracts to the base unit, so a number the UI previews is the number the
 * chain would produce:
 *
 *   roundUpDelta   == contracts/src/libraries/RoundUp.sol  (and engine/src/lib/roundup.ts)
 *   splitByBps     == SweepExecutor._collect  (last leg takes the remainder)
 *   feeOf          == SweepExecutor._settleAsset  (total * feeBps / 10000)
 *   tokensValueUsdg == StockRouter.oracleUsdgFor
 *
 * Units: USDG has 6 decimals (1_000_000n = $1.00); stock tokens have 18;
 * bps are integers with 10_000 = 100%. No floats touch money — floats appear
 * only where a value becomes a progress-bar percentage.
 *
 * validateMix's reasons are built in the live language from the shell namespace
 * (`mixRules.*`). Like spare-chain/errors.ts, this talks to i18next directly, not
 * '@/i18n' (Vite-only), because bun scripts import this file; there errors.ts
 * starts i18next in English with the shell strings.
 */
import i18next from 'i18next';

const tf = i18next.getFixedT(null, 'shell');

/* ------------------------------- constants -------------------------------- */

/** Round-up boundary in whole dollars. */
export type RoundTo = 1 | 5 | 10;
/** Multiplier applied to the round-up delta (1x-5x). */
export type Multiplier = 1 | 2 | 3 | 4 | 5;

export const ROUND_TO_VALUES: readonly RoundTo[] = [1, 5, 10];
export const MULTIPLIER_VALUES: readonly Multiplier[] = [1, 2, 3, 4, 5];

/** $1.00 in USDG base units. */
export const USDG_UNIT = 1_000_000n;
export const USDG_DECIMALS = 6;
export const BPS_TOTAL = 10_000;
export const MAX_UINT64 = (1n << 64n) - 1n;

export function isRoundTo(v: number): v is RoundTo {
  return v === 1 || v === 5 || v === 10;
}

export function isMultiplier(v: number): v is Multiplier {
  return Number.isInteger(v) && v >= 1 && v <= 5;
}

/* -------------------------------- round-up -------------------------------- */

/**
 * Spare change generated by one outgoing payment, in USDG base units.
 *
 * Operation-for-operation identical to RoundUp.delta:
 *   step = roundTo * 1e6; rem = amount % step; rem == 0 ? 0 : (step - rem) * multiplier
 *
 * A payment already on the boundary yields ZERO: rounding $5.00 up to $5.00 is
 * nothing, and adding a full increment would take money the user never agreed
 * to give. Bad roundTo / multiplier throw, as the contract reverts.
 */
export function roundUpDelta(amount: bigint, roundTo: number, multiplier: number): bigint {
  if (!isRoundTo(roundTo)) throw new RangeError(`roundTo must be 1, 5 or 10 (got ${roundTo})`);
  if (!isMultiplier(multiplier)) throw new RangeError(`multiplier must be 1..5 (got ${multiplier})`);
  if (amount <= 0n) return 0n; // uint256 on-chain; a negative UI input means nothing
  const step = BigInt(roundTo) * USDG_UNIT;
  const rem = amount % step;
  if (rem === 0n) return 0n;
  return (step - rem) * BigInt(multiplier);
}

/** The on-chain rule, as RuleRegistry.ruleOf returns it (weeklyCap in base units). */
export interface ChainRule {
  roundTo: number;
  multiplier: number;
  weeklyCap: bigint;
  enabled: boolean;
}

/** A rule accrues only while enabled AND capped above zero (cap 0 = disabled). */
export function ruleIsActive(rule: ChainRule | null | undefined): boolean {
  return !!rule && rule.enabled && rule.weeklyCap > 0n;
}

/** A rule is "set" once roundTo holds a legal value (unset storage reads 0). */
export function ruleIsSet(rule: ChainRule | null | undefined): boolean {
  return !!rule && isRoundTo(rule.roundTo) && isMultiplier(rule.multiplier);
}

/**
 * Round-ups for a batch of payments under a rule, clipped to what the rolling
 * 7-day cap still allows. SweepExecutor reverts any pull that would take the
 * week past `weeklyCap`, so the keeper clips to the room left; the result is
 * what could actually be pulled.
 */
export function accrueBatch(
  amounts: readonly bigint[],
  rule: ChainRule,
  pulledLast7Days = 0n,
): { requested: bigint; accepted: bigint; capped: boolean } {
  if (!ruleIsActive(rule) || !ruleIsSet(rule)) return { requested: 0n, accepted: 0n, capped: false };
  let requested = 0n;
  for (const a of amounts) requested += roundUpDelta(a, rule.roundTo, rule.multiplier);
  const room = rule.weeklyCap > pulledLast7Days ? rule.weeklyCap - pulledLast7Days : 0n;
  const accepted = requested < room ? requested : room;
  return { requested, accepted, capped: accepted < requested };
}

/* ---------------------------------- mix ----------------------------------- */

export interface MixLeg {
  asset: string;
  bps: number;
}

export function bpsTotal(legs: readonly { bps: number }[]): number {
  return legs.reduce((s, l) => s + (Number.isInteger(l.bps) ? l.bps : 0), 0);
}

/**
 * Mirror of ElectionRegistry._validate. Returns a human-readable reason for
 * the first rule a draft breaks, or null when setMix would accept it.
 */
export function validateMix(
  legs: readonly MixLeg[],
  opts: { maxLegs: number; isEligible: (asset: string) => boolean; nameOf?: (asset: string) => string },
): string | null {
  const name = opts.nameOf ?? ((a: string) => a);
  if (legs.length === 0) return tf('mixRules.empty');
  if (legs.length > opts.maxLegs) return tf('mixRules.tooMany', { max: opts.maxLegs });
  const seen = new Set<string>();
  for (const l of legs) {
    const key = l.asset.toLowerCase();
    if (!Number.isInteger(l.bps) || l.bps <= 0) return tf('mixRules.zeroWeight', { asset: name(l.asset) });
    if (!opts.isEligible(l.asset)) return tf('mixRules.inactive', { asset: name(l.asset) });
    if (seen.has(key)) return tf('mixRules.twice', { asset: name(l.asset) });
    seen.add(key);
  }
  const total = bpsTotal(legs);
  if (total !== BPS_TOTAL) return tf('mixRules.total', { total: formatBps(total) });
  return null;
}

/**
 * Split a sweep across a mix exactly as SweepExecutor._collect does: every leg
 * but the last gets floor(amount * bps / 10000); the last takes what is left,
 * so the legs always sum to `amount`.
 */
export function splitByBps<T extends { bps: number }>(amount: bigint, legs: readonly T[]): { leg: T; amount: bigint }[] {
  if (amount <= 0n || legs.length === 0) return [];
  let left = amount;
  return legs.map((leg, i) => {
    const amt = i === legs.length - 1 ? left : (amount * BigInt(leg.bps)) / BigInt(BPS_TOTAL);
    left -= amt;
    return { leg, amount: amt };
  });
}

/** Conversion fee on a leg that actually converts (SweepExecutor._settleAsset). */
export function feeOf(amount: bigint, feeBps: number): bigint {
  if (amount <= 0n || feeBps <= 0) return 0n;
  return (amount * BigInt(feeBps)) / BigInt(BPS_TOTAL);
}

/**
 * Nudge a draft so its weights total exactly 10000 bps. The shortfall (or
 * excess) goes to the largest leg; with every weight at zero it splits evenly,
 * remainder to the first legs. Legs that would go non-positive are left for
 * validateMix to flag rather than silently dropped.
 */
export function balanceBps<T extends MixLeg>(legs: readonly T[]): T[] {
  if (legs.length === 0) return [];
  const total = bpsTotal(legs);
  if (total <= 0) {
    const each = Math.floor(BPS_TOTAL / legs.length);
    let extra = BPS_TOTAL - each * legs.length;
    return legs.map((l) => {
      const add = extra > 0 ? 1 : 0;
      extra -= add;
      return { ...l, bps: each + add };
    });
  }
  const drift = BPS_TOTAL - total;
  if (drift === 0) return legs.slice();
  let big = 0;
  legs.forEach((l, i) => {
    if (l.bps > legs[big].bps) big = i;
  });
  return legs.map((l, i) => (i === big ? { ...l, bps: l.bps + drift } : l));
}

/* ----------------------------- money parsing ------------------------------ */

/**
 * Dollar text -> USDG base units, without ever going through a float.
 * Accepts "12", "12.5", "12.345678", ".5", "$1,250.00". More than 6 decimals,
 * negatives, exponents and junk return null.
 */
export function parseUsd(text: string): bigint | null {
  const t = text.trim().replace(/^\$/, '').replace(/,/g, '');
  const m = /^(\d*)(?:\.(\d{0,6}))?$/.exec(t);
  if (!m || (m[1] === '' && (m[2] === undefined || m[2] === ''))) return null;
  const whole = m[1] === '' ? 0n : BigInt(m[1]);
  const frac = (m[2] ?? '').padEnd(USDG_DECIMALS, '0');
  return whole * USDG_UNIT + BigInt(frac === '' ? '0' : frac);
}

/**
 * Base units -> fixed-point string with `dp` decimals, rounding half-up
 * (away from zero for negatives), with thousands separators on the integer.
 */
export function formatFixed(value: bigint, decimals: number, dp: number): string {
  const neg = value < 0n;
  let v = neg ? -value : value;
  if (dp < decimals) {
    const drop = 10n ** BigInt(decimals - dp);
    v = (v + drop / 2n) / drop;
  } else if (dp > decimals) {
    v = v * 10n ** BigInt(dp - decimals);
  }
  const scale = 10n ** BigInt(dp);
  const whole = (v / scale).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  const frac = dp > 0 ? `.${(v % scale).toString().padStart(dp, '0')}` : '';
  return `${neg && v !== 0n ? '-' : ''}${whole}${frac}`;
}

/** USDG base units -> "$1,234.57". `dp` defaults to cents. */
export function formatUsd(base: bigint, dp = 2): string {
  const s = formatFixed(base, USDG_DECIMALS, dp);
  return s.startsWith('-') ? `-$${s.slice(1)}` : `$${s}`;
}

/** USDG base units -> editable dollar text with no trailing zeros ("12.5"). */
export function usdToInput(base: bigint): string {
  const s = formatFixed(base, USDG_DECIMALS, USDG_DECIMALS).replace(/,/g, '');
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
}

/** Token amount (e.g. 18 dp stock) -> trimmed display with up to `maxDp` decimals. */
export function formatToken(raw: bigint, decimals: number, maxDp = 6): string {
  const s = formatFixed(raw, decimals, maxDp);
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
}

/**
 * USDG (6 dp) a token amount is worth at an 18-dp USD price —
 * StockRouter.oracleUsdgFor: tokens * price / 1e18 / 1e12.
 */
export function tokensValueUsdg(tokens: bigint, price1e18: bigint): bigint {
  if (tokens <= 0n || price1e18 <= 0n) return 0n;
  return (tokens * price1e18) / 10n ** 18n / 10n ** 12n;
}

/** Scale a Chainlink answer to 1e18 (OracleGuard._to1e18). */
export function to1e18(answer: bigint, feedDecimals: number): bigint {
  if (feedDecimals === 18) return answer;
  if (feedDecimals < 18) return answer * 10n ** BigInt(18 - feedDecimals);
  return answer / 10n ** BigInt(feedDecimals - 18);
}

/** part/whole as a 0..100 percentage for bars only (two-decimal precision). */
export function pctOf(part: bigint, whole: bigint): number {
  if (whole <= 0n || part <= 0n) return 0;
  if (part >= whole) return 100;
  return Number((part * 10_000n) / whole) / 100;
}

/* --------------------------------- weights -------------------------------- */

/** "33.33" -> 3333 bps. Up to 2 decimals, 0..100. null for anything else. */
export function parsePct(text: string): number | null {
  const t = text.trim().replace(/%$/, '');
  const m = /^(\d{1,3})(?:\.(\d{0,2}))?$/.exec(t);
  if (!m) return null;
  const bps = Number(m[1]) * 100 + Number((m[2] ?? '').padEnd(2, '0') || '0');
  return bps > BPS_TOTAL ? null : bps;
}

/** 3333 -> "33.33", 2500 -> "25". */
export function formatBps(bps: number): string {
  const whole = Math.trunc(bps / 100);
  const frac = Math.abs(bps % 100);
  return frac === 0 ? String(whole) : `${whole}.${String(frac).padStart(2, '0').replace(/0$/, '')}`;
}

/* ---------------------------------- epochs -------------------------------- */

/** SweepExecutor.currentEpoch: floor(ts / epochLength) + 1. */
export function epochAt(tsSec: bigint, epochLength: bigint): bigint {
  return tsSec / epochLength + 1n;
}

/** Unix second at which the epoch after the one containing `tsSec` begins. */
export function nextEpochStart(tsSec: bigint, epochLength: bigint): bigint {
  return (tsSec / epochLength + 1n) * epochLength;
}
