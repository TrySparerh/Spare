#!/usr/bin/env node
// Tiny JSON helper for the SPARE shell scripts. Runs under bun or node; no deps.
//
//   spare-json.mjs get <file> <dot.path>
//       print a value (strings raw, everything else as JSON); exit 1 if missing
//
//   spare-json.mjs dev-config <in.json> <out.json> <chainId> <owner> <keeper> <pauser> <attestor>
//       derive a LOCAL-FORK config from the mainnet config: same assets, pool keys,
//       mix and params; roles replaced with the given (anvil test) addresses;
//       screening off. Refuses to write a config for chain 4663.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const [cmd, ...args] = process.argv.slice(2);
const fail = (msg) => {
  process.stderr.write(`spare-json: ${msg}\n`);
  process.exit(1);
};
const read = (f) => JSON.parse(readFileSync(f, "utf8"));
const isAddr = (a) => /^0x[0-9a-fA-F]{40}$/.test(a);

if (cmd === "get") {
  const [file, path] = args;
  if (!file || !path) fail("usage: get <file> <dot.path>");
  let v = read(file);
  for (const k of path.split(".")) {
    if (v === null || typeof v !== "object" || !(k in v)) fail(`${path} not found in ${file}`);
    v = v[k];
  }
  process.stdout.write(typeof v === "string" ? v : JSON.stringify(v));
  process.stdout.write("\n");
} else if (cmd === "dev-config") {
  const [inp, out, chainId, owner, keeper, pauser, attestor] = args;
  if (!attestor) fail("usage: dev-config <in> <out> <chainId> <owner> <keeper> <pauser> <attestor>");
  if (Number(chainId) === 4663) fail("refusing to generate a dev config for chain 4663");
  for (const a of [owner, keeper, pauser, attestor]) if (!isAddr(a)) fail(`not an address: ${a}`);
  const src = read(inp);
  const rest = src;
  const cfg = {
    _generated: `GENERATED by scripts/dev-fork.sh from ${basename(inp)} - do not edit. Local anvil fork only: anvil test-key roles, screening off. Assets, pool keys, mix and params are the mainnet config's.`,
    ...rest,
    network: `anvil-fork-of-${src.network}`,
    chainId: Number(chainId),
    roles: { owner, keeper, pauser, attestor },
    screening: { ...src.screening, enforced: false },
  };
  writeFileSync(out, JSON.stringify(cfg, null, 2) + "\n");
} else {
  fail("commands: get | dev-config");
}
