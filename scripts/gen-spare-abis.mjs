#!/usr/bin/env node
/**
 * Regenerates src/lib/spare-chain/abis.ts from the Foundry deploy artifacts.
 *
 *   node scripts/gen-spare-abis.mjs
 *
 * Source: contracts/out-deploy/<Name>.sol/<Name>.json (field `abi`). The
 * Solidity in contracts/src is the source of truth; rebuild the artifacts with
 * forge first if the contracts changed, then run this.
 *
 * Each ABI is emitted `as const` so viem/wagmi infer argument and return types.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'contracts', 'out-deploy');
const target = join(root, 'src', 'lib', 'spare-chain', 'abis.ts');

/**
 * [artifact, exported identifier, one-line description]. `artifact` is
 * `<Name>` for `<Name>.sol/<Name>.json`, or `<File>.sol/<Name>` when the
 * interface lives in a differently named source file.
 */
const CONTRACTS = [
  ['AssetRegistry', 'assetRegistryAbi', 'eligible universe: tokens(), get(token), isEligible(token)'],
  ['RuleRegistry', 'ruleRegistryAbi', 'wallet links + round-up rule per account'],
  ['ElectionRegistry', 'electionRegistryAbi', 'target mix per account (Leg[] of asset + bps)'],
  ['ScreeningGate', 'screeningGateAbi', 'buy eligibility (enforcement off at launch)'],
  ['StockRouter', 'stockRouterAbi', 'oracleStatus(token) + allowlisted v4 swaps'],
  ['CashPark', 'cashParkAbi', 'spare waiting between accrual and sweep; exit()'],
  ['FeeVault', 'feeVaultAbi', 'conversion-fee sink'],
  ['SweepExecutor', 'sweepExecutorAbi', 'accrual pulls, sweeps, deliveries, claims'],
  ['IAllowanceTransfer', 'permit2Abi', 'Uniswap Permit2 allowance surface (approve / allowance)'],
  ['IExternal.sol/IAggregatorV3', 'aggregatorV3Abi', 'Chainlink feed (last price, shown when the oracle guard says STALE)'],
];

const parts = [
  '/**',
  ' * AUTO-GENERATED by scripts/gen-spare-abis.mjs — do not edit by hand.',
  ' * Source: contracts/out-deploy/<Name>.sol/<Name>.json (Foundry artifacts).',
  ' * Regenerate: node scripts/gen-spare-abis.mjs',
  ' */',
  '',
];

for (const [name, ident, about] of CONTRACTS) {
  const file = name.includes('/')
    ? join(outDir, ...`${name}.json`.split('/'))
    : join(outDir, `${name}.sol`, `${name}.json`);
  const artifact = JSON.parse(readFileSync(file, 'utf8'));
  if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
    throw new Error(`${relative(root, file)} has no abi`);
  }
  parts.push(`/** ${name.split('/').pop()} — ${about}. */`);
  parts.push(`export const ${ident} = ${JSON.stringify(artifact.abi, null, 2)} as const;`);
  parts.push('');
}

writeFileSync(target, parts.join('\n'));
console.log(`wrote ${relative(root, target)} (${CONTRACTS.length} ABIs)`);
